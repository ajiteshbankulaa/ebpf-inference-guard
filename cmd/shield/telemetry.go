// Must match SAMPLE_FACTOR in the C program.
const samplingFactor = 64

// Features given to our rule or ML detector.
type Features struct {
	PPS             float64
	SynRatio        float64
	MeanPacketBytes float64
	IATCV           float64
}

// Configuration for the telemetry/detection pipeline.
type monitorConfig struct {
	Mode         string
	PPSThreshold float64
	MinSamples   int
	AutoTTL      time.Duration
	CSVPath      string
	Label        int
	RunID        string
}

// Statistics collected for one source IP
// during one time window.
type flowWindow struct {
	samples  int
	tcp      int
	syn      int
	bytes    uint64
	lastTS   uint64
	gaps     int
	gapSum   float64
	gapSqSum float64
}

// Add a sampled packet to this IP's window.
func (w *flowWindow) observe(e shieldFlowEvent) {
	w.samples++
	w.bytes += uint64(e.PktLen)

	// IPv4 protocol 6 = TCP.
	if e.Protocol == 6 {
		w.tcp++

		// SYN set, ACK not set.
		if e.TcpFlags&0x02 != 0 &&
			e.TcpFlags&0x10 == 0 {
			w.syn++
		}
	}

	// Calculate gap from the previous sampled event.
	if w.lastTS != 0 && e.TsNs > w.lastTS {
		gap := float64(e.TsNs-w.lastTS) / 1e9

		w.gaps++
		w.gapSum += gap
		w.gapSqSum += gap * gap
	}

	if e.TsNs > w.lastTS {
		w.lastTS = e.TsNs
	}
}

// Turn accumulated observations into four features.
func (w *flowWindow) features(seconds float64) Features {
	if w.samples == 0 || seconds <= 0 {
		return Features{}
	}

	f := Features{
		PPS: float64(w.samples*samplingFactor) / seconds,

		MeanPacketBytes: float64(w.bytes) /
			float64(w.samples),
	}

	if w.tcp > 0 {
		f.SynRatio = float64(w.syn) /
			float64(w.tcp)
	}

	// Need at least two observed gaps for variability.
	if w.gaps >= 2 && w.gapSum > 0 {
		mean := w.gapSum / float64(w.gaps)

		variance := w.gapSqSum/float64(w.gaps) -
			mean*mean

		// Protect against tiny floating-point errors.
		if variance < 0 {
			variance = 0
		}

		f.IATCV = math.Sqrt(variance) / mean
	}

	return f
}

// Convert a generated source-IP field to readable IPv4.
func eventSource(e shieldFlowEvent) netip.Addr {
	var octets [4]byte

	binary.NativeEndian.PutUint32(
		octets[:],
		e.SrcIp,
	)

	return netip.AddrFrom4(octets)
}

// Read binary events from the kernel and send
// them into a buffered Go channel.
func readSamples(
	reader *ringbuf.Reader,
	out chan<- shieldFlowEvent,
	lost *atomic.Uint64,
	done chan<- struct{},
) {
	defer close(done)

	for {
		rec, err := reader.Read()

		if err != nil {
			if !errors.Is(err, os.ErrClosed) {
				log.Printf("ring read error: %v", err)
			}
			return
		}

		// This type is generated by bpf2go.
		var ev shieldFlowEvent

		err = binary.Read(
			bytes.NewReader(rec.RawSample),
			binary.NativeEndian,
			&ev,
		)

		if err != nil {
			log.Printf("invalid event: %v", err)
			continue
		}

		// Don't block forever if our aggregator is slow.
		select {
		case out <- ev:
		default:
			lost.Add(1)
		}
	}
}

// Main telemetry aggregation and detection loop.
func runMonitor(
	ctx context.Context,
	reader *ringbuf.Reader,
	blocklist *ebpf.Map,
	cfg monitorConfig,
) {
	var file *os.File
	var writer *csv.Writer

	// Optional CSV data collection.
	if cfg.CSVPath != "" {
		err := os.MkdirAll(
			filepath.Dir(cfg.CSVPath),
			0755,
		)
		if err != nil {
			log.Printf("CSV directory error: %v", err)
			return
		}

		file, err = os.OpenFile(
			cfg.CSVPath,
			os.O_CREATE|os.O_APPEND|os.O_WRONLY,
			0644,
		)
		if err != nil {
			log.Printf("CSV open error: %v", err)
			return
		}
		defer file.Close()

		info, err := file.Stat()
		if err != nil {
			log.Printf("CSV stat error: %v", err)
			return
		}

		writer = csv.NewWriter(file)

		if info.Size() == 0 {
			header := []string{
				"pps",
				"syn_ratio",
				"mean_packet_bytes",
				"iat_cv",
				"label",
				"run_id",
				"samples",
			}

			if err := writer.Write(header); err != nil {
				log.Printf("CSV header error: %v", err)
				return
			}
			writer.Flush()
		}

		log.Printf(
			"Recording run=%s label=%d to %s",
			cfg.RunID, cfg.Label, cfg.CSVPath,
		)
	}

	// Channel between ring reader and aggregator.
	events := make(chan shieldFlowEvent, 8192)

	var userLost atomic.Uint64
	readDone := make(chan struct{})

	go readSamples(reader, events, &userLost, readDone)

	// Close reader and flush CSV on shutdown.
	defer func() {
		_ = reader.Close()
		<-readDone

		if writer != nil {
			writer.Flush()
			if err := writer.Error(); err != nil {
				log.Printf("CSV flush error: %v", err)
			}
		}
	}()

	// One accumulator per source IP.
	windows := make(map[netip.Addr]*flowWindow)

	// Avoid repeatedly blocking the same IP.
	blockCooldown := make(map[netip.Addr]time.Time)

	ticker := time.NewTicker(time.Second)
	defer ticker.Stop()

	previous := time.Now()

	for {
		select {
		case <-ctx.Done():
			return

		// New sampled event from XDP.
		case ev := <-events:
			src := eventSource(ev)

			w := windows[src]
			if w == nil {
				w = &flowWindow{}
				windows[src] = w
			}

			w.observe(ev)

		// One-second window finished.
		case now := <-ticker.C:
			seconds := now.Sub(previous).Seconds()
			previous = now

			for src, w := range windows {
				f := w.features(seconds)

				log.Printf(
					"[WINDOW] ip=%s samples=%d pps=%.0f syn=%.2f mean=%.0f cv=%.2f",
					src,
					w.samples,
					f.PPS,
					f.SynRatio,
					f.MeanPacketBytes,
					f.IATCV,
				)

				// Save the measured features if enabled.
				if writer != nil {
					row := []string{
						fmt.Sprintf("%.6f", f.PPS),
						fmt.Sprintf("%.6f", f.SynRatio),
						fmt.Sprintf("%.6f", f.MeanPacketBytes),
						fmt.Sprintf("%.6f", f.IATCV),
						strconv.Itoa(cfg.Label),
						cfg.RunID,
						strconv.Itoa(w.samples),
					}

					if err := writer.Write(row); err != nil {
						log.Printf("CSV write error: %v", err)
					}
				}

				// Never decide from tiny windows.
				if w.samples < cfg.MinSamples {
					continue
				}

				// Observation-only mode.
				if cfg.Mode == "off" {
					continue
				}

				malicious := false

				switch cfg.Mode {
				case "rules":
					malicious =
						f.PPS > cfg.PPSThreshold &&
							f.SynRatio > 0.60

				case "tree":
					malicious = predictTree(f)
				}

				if !malicious {
					continue
				}

				// Don't repeatedly replace the same block.
				if now.Before(blockCooldown[src]) {
					continue
				}

				err := addBlockWithReason(
					blocklist,
					src.String(),
					cfg.AutoTTL,
					2, // Reason 2 = automatic detection.
				)
				if err != nil {
					log.Printf("auto-block failed: %v", err)
					continue
				}

				blockCooldown[src] = now.Add(cfg.AutoTTL)

				log.Printf(
					"[BLOCK] ip=%s mode=%s pps=%.0f syn=%.2f mean=%.0f cv=%.2f ttl=%s",
					src,
					cfg.Mode,
					f.PPS,
					f.SynRatio,
					f.MeanPacketBytes,
					f.IATCV,
					cfg.AutoTTL,
				)
			}

			// Flush any recorded windows to disk.
			if writer != nil {
				writer.Flush()

				if err := writer.Error(); err != nil {
					log.Printf("CSV error: %v", err)
				}
			}

			// Start a fresh tumbling window.
			windows = make(map[netip.Addr]*flowWindow)

			// Remove stale entries from Go cooldown state.
			for src, until := range blockCooldown {
				if !now.Before(until) {
					delete(blockCooldown, src)
				}
			}

			if n := userLost.Swap(0); n > 0 {
				log.Printf(
					"[WARN] userspace event loss=%d", n,
				)
			}
		}
	}
}
