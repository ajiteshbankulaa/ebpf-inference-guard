
#!/usr/bin/env python3

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from sklearn.tree import DecisionTreeClassifier, export_text
from sklearn.metrics import confusion_matrix, classification_report


# These names must match the CSV columns written by Go.
FEATURES = [
    "pps",
    "syn_ratio",
    "mean_packet_bytes",
    "iat_cv",
]

# These names must match the Go Features struct fields.
GO_FIELDS = [
    "PPS",
    "SynRatio",
    "MeanPacketBytes",
    "IATCV",
]


def export_model_to_go(model, output_path):
    """
    Convert a trained sklearn decision tree
    into ordinary Go if-statements.
    """

    tree = model.tree_

    lines = [
        "// Code generated by ml/train.py.",
        "// Do not edit manually.",
        "",
        "package main",
        "",
        "const treeTrained = true",
        "",
        "func predictTree(f Features) bool {",
    ]

    def visit(node, indent):
        """
        Recursively translate each decision-tree node.
        """

        left = int(tree.children_left[node])
        right = int(tree.children_right[node])

        prefix = "    " * indent

        # A leaf has no children.
        if left == -1 and right == -1:
            class_index = int(
                np.argmax(tree.value[node][0])
            )

            predicted_label = int(
                model.classes_[class_index]
            )

            result = (
                "true" if predicted_label == 1
                else "false"
            )

            lines.append(f"{prefix}return {result}")
            return

        # Internal node: identify feature and threshold.
        feature_index = int(tree.feature[node])
        threshold = float(tree.threshold[node])

        go_field = GO_FIELDS[feature_index]

        # Left child: feature <= threshold.
        lines.append(
            f"{prefix}if f.{go_field} <= "
            f"{threshold:.17g} {{"
        )

        visit(left, indent + 1)

        lines.append(f"{prefix}}}")

        # Right child: feature > threshold.
        # The left branch already returns.
        visit(right, indent)

    # Node 0 is the root.
    visit(0, 1)

    lines.append("}")
    lines.append("")

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    output_path.write_text(
        "\n".join(lines),
        encoding="utf-8",
    )


def main():
    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--csv",
        default="data/windows.csv",
    )

    parser.add_argument(
        "--output",
        default="cmd/shield/model_generated.go",
    )

    parser.add_argument(
        "--min-samples",
        type=int,
        default=5,
    )

    args = parser.parse_args()

    if args.min_samples < 1:
        raise ValueError(
            "--min-samples must be positive"
        )

    # ------------------------------------------------
    # 1. Load the measurements.
    # ------------------------------------------------

    df = pd.read_csv(args.csv)

    required = FEATURES + [
        "label",
        "run_id",
        "samples",
    ]

    missing = [
        column for column in required
        if column not in df.columns
    ]

    if missing:
        raise ValueError(
            f"Missing columns: {missing}"
        )

    # Keep only known labels and sufficiently
    # sampled windows.
    df = df[
        df["label"].isin([0, 1]) &
        (df["samples"] >= args.min_samples)
    ].copy()

    if df.empty:
        raise ValueError(
            "No usable windows. Collect more data."
        )

    # Reject invalid numerical data.
    values = df[FEATURES].to_numpy(dtype=float)

    if not np.isfinite(values).all():
        raise ValueError(
            "Feature data contains NaN or infinity."
        )

    if df["run_id"].isna().any():
        raise ValueError(
            "Every row needs an experiment run_id."
        )

    # Each run must represent only one label.
    run_labels = df.groupby("run_id")["label"].nunique()

    if (run_labels > 1).any():
        raise ValueError(
            "A run_id contains conflicting labels."
        )

    # ------------------------------------------------
    # 2. Split by experiment, not individual window.
    # ------------------------------------------------

    train_runs = set()
    test_runs = set()

    for label in [0, 1]:
        runs = sorted(
            df.loc[
                df["label"] == label,
                "run_id"
            ].unique().tolist()
        )

        if len(runs) < 2:
            raise ValueError(
                f"Need at least two runs for label "
                f"{label}. Found: {runs}"
            )

        # Hold out the last named run in each class.
        train_runs.update(runs[:-1])
        test_runs.add(runs[-1])

    train = df[
        df["run_id"].isin(train_runs)
    ].copy()

    test = df[
        df["run_id"].isin(test_runs)
    ].copy()

    print("Training runs:", sorted(train_runs))
    print("Test runs:", sorted(test_runs))
    print("Training windows:", len(train))
    print("Testing windows:", len(test))

    # ------------------------------------------------
    # 3. Train a shallow decision tree.
    # ------------------------------------------------

    model = DecisionTreeClassifier(
        max_depth=4,
        class_weight="balanced",
        random_state=7,
    )

    model.fit(
        train[FEATURES],
        train["label"],
    )

    # ------------------------------------------------
    # 4. Evaluate the model on held-out runs.
    # ------------------------------------------------

    predictions = model.predict(
        test[FEATURES]
    )

    print("\nConfusion matrix:")
    print(
        confusion_matrix(
            test["label"],
            predictions,
            labels=[0, 1],
        )
    )

    print("\nClassification report:")
    print(
        classification_report(
            test["label"],
            predictions,
            labels=[0, 1],
            zero_division=0,
        )
    )

    print("\nLearned decision tree:")
    print(
        export_text(
            model,
            feature_names=FEATURES,
        )
    )

    # ------------------------------------------------
    # 5. Export to standalone Go source code.
    # ------------------------------------------------

    output_path = Path(args.output)

    export_model_to_go(model, output_path)

    print(f"\nGenerated Go model: {output_path}")
    print(
        "Remember: these are small-lab evaluation "
        "results, not production accuracy estimates."
    )


if __name__ == "__main__":
    main()
